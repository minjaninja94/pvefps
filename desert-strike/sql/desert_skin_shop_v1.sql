create function private.desert_skin_state() returns jsonb language plpgsql security definer set search_path='' as $$
declare u uuid:=auth.uid(); w public.desert_skin_wallets%rowtype; bonus integer:=0; inserted integer; today date:=(now() at time zone 'Asia/Seoul')::date;
begin
 if u is null or not exists(select 1 from public.desert_web_members where user_id=u) then raise exception '회원 로그인이 필요합니다.' using errcode='42501'; end if;
 insert into public.desert_skin_wallets(user_id) values(u) on conflict do nothing;
 get diagnostics inserted=row_count;
 select * into w from public.desert_skin_wallets where user_id=u for update;
 if inserted=1 then bonus:=3000;
 elsif w.last_login_date<today then
  bonus:=300;
  update public.desert_skin_wallets set points=points+300,last_login_date=today where user_id=u returning * into w;
 end if;
 return jsonb_build_object('points',w.points,'grant',bonus,'lastLoginDate',w.last_login_date,
 'owned',coalesce((select jsonb_agg(skin_id order by skin_id) from public.desert_skin_unlocks where user_id=u),'[]'::jsonb));
end; $$;
create function private.desert_buy_skin(p_skin text) returns jsonb language plpgsql security definer set search_path='' as $$
declare u uuid:=auth.uid(); s public.desert_skin_catalog%rowtype; state jsonb; remaining integer;
begin
 state:=private.desert_skin_state();
 select * into s from public.desert_skin_catalog where id=p_skin;
 if not found then raise exception '알 수 없는 스킨입니다.' using errcode='22023'; end if;
 if s.price=0 or exists(select 1 from public.desert_skin_unlocks where user_id=u and skin_id=p_skin) then return state; end if;
 if s.chroma<>'original' and s.base_id not in ('default','moe') and not exists(select 1 from public.desert_skin_unlocks where user_id=u and skin_id=s.base_id) then
  raise exception '기본 스킨을 먼저 해금해 주세요.' using errcode='22023';
 end if;
 update public.desert_skin_wallets set points=points-s.price where user_id=u and points>=s.price returning points into remaining;
 if not found then raise exception '스킨 포인트가 부족합니다.' using errcode='22023'; end if;
 insert into public.desert_skin_unlocks(user_id,skin_id) values(u,p_skin);
 return jsonb_set(private.desert_skin_state(),'{grant}',state->'grant');
end; $$;
