create function private.desert_check_selected_skin() returns trigger language plpgsql security definer set search_path='' as $$
begin
 if not exists(select 1 from public.desert_skin_catalog c where c.id=new.selected_skin
  and (c.faction is null or c.faction=new.selected_faction)
  and (c.price=0 or exists(select 1 from public.desert_skin_unlocks s where s.user_id=new.user_id and s.skin_id=c.id))) then
  raise exception '해금된 스킨만 선택할 수 있습니다.' using errcode='42501';
 end if;
 return new;
end; $$;
