'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=__dirname;
const icon=fs.readFileSync(path.join(root,'assets/brand/desert-front-icon.webp'));
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const css=fs.readFileSync(path.join(root,'style-v2.css'),'utf8');
assert.equal(icon.subarray(0,4).toString(),'RIFF','favicon must be real binary WebP, not a filename stub');
assert.equal(icon.subarray(8,12).toString(),'WEBP');
assert.ok(icon.length>1500,'portrait image must be populated');
assert.match(html,/<link rel="icon"[^>]*desert-front-icon\.webp/);
assert.match(html,/<link rel="apple-touch-icon"[^>]*desert-front-icon\.webp/);
assert.match(html,/<img class="lobby-mark"[^>]*desert-front-icon\.webp/);
assert.match(html,/<img class="logo-badge"[^>]*desert-front-icon\.webp/);
assert.doesNotMatch(html,/D<span>\/{3}<\/span>F/,'all D///F emblems must be replaced');
assert.match(css,/\.lobby-header \.lobby-mark\{/);
assert.match(css,/\.logo img\.logo-badge\{/);
assert.ok((html.match(/desert-front-icon\.webp/g)||[]).length>=4,'browser and both logos share same artwork');
console.log('Desert Front original soldier image uploaded: browser favicon, touch icon, lobby and in-game HUD verified.');
