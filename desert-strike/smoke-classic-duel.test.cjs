'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const win={},context={window:win,Math,Map,Set,Number,Object,Array,console};
for(const script of ['unit-consolidation.js','defense-guardian.js','hard-ai.js','tri-lane-engine.js']){
 vm.runInNewContext(fs.readFileSync(path.join(__dirname,script),'utf8'),context,{timeout:12000,filename:script});
}
const engine=win.DesertTriEngine;
const users=[{uid:'home',team:0,faction:4},{uid:'away',team:1,faction:9}];
const classic=engine.create({mode:'classic',size:1,members:users});
const state=classic.state;
assert.equal(state.mode,'classic');
assert.equal(state.width,3300);
assert.equal(state.height,520,'classic match must use exactly the solo map height');
assert.equal(state.lanes,1);
assert.equal(state.players.length,2);
assert.deepEqual(Array.from(state.cores),[[7200,7200]],'classic core HP mirrors solo');
for(const p of state.players){
 assert.equal(p.buildings.length,1,'one 75-slot factory per human');
 assert.equal(p.buildings[0].length,75);
 assert.equal(p.cash,360,'same opening credits as solo');
}
assert.equal(classic.order('home',{type:'build',lane:1,slot:0,role:0}).ok,false,'an unowned line cannot be ordered');
assert.equal(classic.order('home',{type:'build',lane:2,slot:0,role:0}).ok,false);
assert.equal(classic.order('home',{type:'build',lane:0,slot:0,role:0}).ok,true);
assert.equal(classic.order('away',{type:'build',lane:0,slot:1,role:1}).ok,true);
const enemyCredits=state.players[1].cash;
assert.equal(classic.order('home',{type:'build',lane:0,slot:1,role:1}).ok,true,'both sides can own the same slot index');
assert.equal(state.players[1].cash,enemyCredits,'player builds may not debit their opponent');
assert.equal(classic.order('home',{type:'build',lane:0,slot:0,role:3}).ok,false,'occupied buildings cannot be overwritten without demolition');
state.next=.01;classic.tick(.2);
assert.ok(state.units.some(u=>u.team===0&&u.lane===0),'first wave spawns home team');
assert.ok(state.units.some(u=>u.team===1&&u.lane===0),'first wave spawns away team');
assert.ok(state.units.every(u=>u.y>=0&&u.y<=520&&u.lane===0),'every actor stays in one 520-height arena');
const redacted=classic.snapshot('home'),other=classic.snapshot('away');
assert.equal(redacted.height,520);
assert.equal(redacted.lanes,1);
assert.equal(redacted.coreMaxHP,7200);
assert.equal(redacted.mode,'classic');
assert.equal(redacted.players[0].cash,state.players[0].cash);
assert.equal(redacted.players[1].cash,null,'opponent credits remain private');
assert.equal(other.players[0].cash,null,'privacy is symmetric');
assert.equal(classic.order('home',{type:'upgrade',kind:'weapon'}).ok,true,'classic has the same authoritative upgrade controls');
state.cores[0][1]=0;
classic.tick(.16);
assert.equal(state.ended,true,'classic match ends when the sole enemy core is destroyed');
assert.equal(state.winner,0,'one core victory belongs to correct team');
assert.equal(classic.order('away',{type:'build',lane:0,slot:2,role:0}).ok,false,'no orders after defeat');
const triple=engine.create({mode:'pvp',size:1,members:users});
assert.equal(triple.state.height,1560,'existing PvP arena must not be reduced');
assert.equal(triple.state.lanes,3);
assert.equal(triple.state.players[0].buildings.length,3);
assert.equal(triple.state.cores.length,3);
const coop=engine.create({mode:'coop',size:2,members:[{uid:'co1',team:0,faction:0},{uid:'co2',team:0,faction:1}]});
assert.equal(coop.state.height,1560);
assert.equal(coop.state.players.length,4,'existing co-op bots remain intact');
assert.throws(()=>engine.create({mode:'classic',size:2,members:users}),/경기 모드/);
assert.throws(()=>engine.create({mode:'classic',size:1,members:[users[0]]}),/인원/);
const net=fs.readFileSync(path.join(__dirname,'tri-lane-network.js'),'utf8');
assert.match(net,/\['pvp','coop','classic'\]/,'classic must be whitelisted for online room creation');
assert.match(net,/data\.state\.lanes!==\(data\.state\.mode==='classic'\?1:3\)/,'guest must validate real map lane counts');
const html=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
assert.match(html,/<option value="classic">클래식 1:1/,'lobby must offer the playable classic option');
console.log('Classic 1v1 passed: 3300x520 map, 7200-HP core, one 75-slot production grid, 1v1 economy, deployment, scouting privacy, tech, single-core victory, and triple PvP/coop compatibility.');
